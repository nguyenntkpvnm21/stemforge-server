const { randomUUID } = require('node:crypto');
const cloudinary = require('../config/cloudinary');

const ALLOWED_FORMATS = ['mp3', 'wav', 'flac'];

class AudioUploadError extends Error {
  constructor(code, status, message) {
    super(message);

    this.name = 'AudioUploadError';
    this.code = code;
    this.status = status;
  }
}

function uploadBuffer(buffer, publicId) {
  return new Promise((resolve, reject) => {
    const stream = cloudinary.uploader.upload_stream(
      {
        resource_type: 'video',
        type: 'upload',
        public_id: publicId,
        overwrite: false,
        allowed_formats: [...ALLOWED_FORMATS],
        timeout: 60000,
        disable_promise: true,
      },
      (error, result) => {
        if (error) {
          reject(error);
          return;
        }

        resolve(result);
      }
    );

    stream.on('error', reject);
    stream.end(buffer);
  });
}

function hasHttpsUrl(value) {
  if (typeof value !== 'string' || value.length === 0) {
    return false;
  }

  try {
    return new URL(value).protocol === 'https:';
  } catch {
    return false;
  }
}

function validateResult(result, publicId) {
  if (
    !result ||
    result.public_id !== publicId ||
    result.resource_type !== 'video' ||
    result.type !== 'upload' ||
    typeof result.format !== 'string'
  ) {
    return new AudioUploadError(
      'INVALID_UPLOAD_RESULT',
      502,
      'Audio storage returned an invalid response.'
    );
  }

  if (!ALLOWED_FORMATS.includes(result.format)) {
    return new AudioUploadError(
      'UNSUPPORTED_AUDIO',
      415,
      'Only valid MP3, WAV, and FLAC audio files are supported.'
    );
  }

  if (
    !hasHttpsUrl(result.secure_url) ||
    !Number.isFinite(result.duration) ||
    result.duration <= 0 ||
    !Number.isSafeInteger(result.bytes) ||
    result.bytes <= 0
  ) {
    return new AudioUploadError(
      'INVALID_AUDIO_METADATA',
      502,
      'Audio storage returned invalid audio metadata.'
    );
  }

  return null;
}

async function cleanupRejectedUpload(publicId) {
  try {
    const result = await cloudinary.uploader.destroy(publicId, {
      resource_type: 'video',
      type: 'upload',
      invalidate: true,
      timeout: 15000,
    });

    if (!['ok', 'not found'].includes(result?.result)) {
      throw new Error('Unexpected asset deletion response.');
    }
  } catch (error) {
    console.error(
      'Rejected audio cleanup failed:',
      publicId,
      error.name || 'Error',
      error.http_code || ''
    );

    throw new AudioUploadError(
      'AUDIO_CLEANUP_FAILED',
      502,
      'Unable to finish processing the audio upload.'
    );
  }
}

async function uploadAudioBuffer(buffer, ownerId) {
  if (!Buffer.isBuffer(buffer) || buffer.length === 0) {
    throw new TypeError('A non-empty audio buffer is required.');
  }

  if (
    typeof ownerId !== 'string' ||
    !/^[a-fA-F0-9]{24}$/.test(ownerId)
  ) {
    throw new TypeError('A valid owner ID is required.');
  }

  const publicId = `stemforge/audio/${ownerId}/${randomUUID()}`;

  let result;

  try {
    result = await uploadBuffer(buffer, publicId);
  } catch (error) {
    const message =
      typeof error?.message === 'string' ? error.message : '';

    const isRejectedMedia =
      error?.http_code === 400 &&
      /invalid (audio|video|file)|unsupported.*format|format.*not allowed/i
        .test(message);

    if (isRejectedMedia) {
      throw new AudioUploadError(
        'UNSUPPORTED_AUDIO',
        415,
        'Only valid MP3, WAV, and FLAC audio files are supported.'
      );
    }

    throw new AudioUploadError(
      'AUDIO_UPLOAD_FAILED',
      502,
      'Unable to upload audio. Please try again later.'
    );
  }

  const validationError = validateResult(result, publicId);

  if (validationError) {
    // Delete only the ID generated by this upload attempt.
    await cleanupRejectedUpload(publicId);
    throw validationError;
  }

  return {
    audioUrl: result.secure_url,
    duration: result.duration,
    fileSize: result.bytes,
    publicId: result.public_id,
  };
}

module.exports = {
  uploadAudioBuffer,
  AudioUploadError,
};